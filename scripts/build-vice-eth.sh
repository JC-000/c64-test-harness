#!/usr/bin/env bash
# build-vice-eth.sh -- Homebrew's VICE, with ethernet that works without root (macOS).
#
# Stock VICE enables its pcap ethernet driver only for root
# (archdep_rawnet_capability(): geteuid() == 0, or CAP_NET_RAW on Linux), so
# on macOS a VICE ethernet launch needs sudo for x64sc.  macOS grants packet
# capture through the permissions on /dev/bpf* instead (Wireshark's ChmodBPF
# makes them root:access_bpf 0660).  vice/rawnet-bpf-permissions.patch adds
# that check -- can this user open a /dev/bpf* node read-write? -- and makes
# the binary say so in `x64sc -features` (RAWNET_BPF_PERMISSIONS yes), which
# is how the harness decides whether a launch needs root.
#
# The build follows the mainstream release by construction: the formula is
# regenerated from Homebrew's vice formula on every run, so it is the same
# upstream tarball, the same Homebrew backports, the same configure flags and
# the same dependencies, plus that one patch.  It installs keg-only as
# `vice-eth` from a local tap, so it never replaces or shadows `vice`.
# `--check` reports a build left behind by a `brew upgrade vice` (or by a
# change to the patch) as stale; verify-dev-env.sh runs it.
#
# Homebrew's vice formula is the file `brew info --json=v2 vice` names
# (ruby_source_path in homebrew-core at tap_git_head), fetched from GitHub and
# verified against the API's ruby_source_checksum -- what Homebrew itself does
# in API mode, where homebrew/core is not tapped and `brew cat vice` fails.
# `brew cat vice` is the fallback when homebrew/core is tapped.  A locally
# edited vice.rb in a tapped homebrew/core is never built from: in API mode
# brew info does not read it, and with HOMEBREW_NO_INSTALL_FROM_API=1 its
# checksum will not match the pinned download, so the script exits 2.
#
# Usage:
#   scripts/build-vice-eth.sh                 build, or do nothing when current
#   scripts/build-vice-eth.sh --force         rebuild even when current
#   scripts/build-vice-eth.sh --check         exit 0 current, 1 stale or diverged (still
#                                             runs as you), 2 not built or not patched,
#                                             3 built and patched but not comparable
#                                             (Homebrew's formula could not be read)
#   scripts/build-vice-eth.sh --print-formula print the generated formula only
#
# Requires macOS and Homebrew.  Never uses sudo.

set -euo pipefail

TAP="c64-test-harness/local"
NAME="vice-eth"
MARKER="RAWNET_BPF_PERMISSIONS"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PATCH="$REPO_ROOT/vice/rawnet-bpf-permissions.patch"
# Where homebrew-core's files are served by commit (tests point it at file://).
CORE_RAW_URL="${C64H_HOMEBREW_CORE_RAW_URL:-https://raw.githubusercontent.com/Homebrew/homebrew-core}"

die() { printf 'build-vice-eth: %s\n' "$1" >&2; exit "${2:-1}"; }
say() { printf 'build-vice-eth: %s\n' "$1"; }

sha256_of() { shasum -a 256 | awk '{print $1}'; }

# The patch as the formula fetches it: a copy inside the tap, so the
# installed formula does not depend on where this checkout lives.
tap_patch() { printf '%s/patches/rawnet-bpf-permissions.patch\n' "$(brew --repository "$TAP")"; }

# generate_formula <source-formula-sha> <patch-sha> < Homebrew's vice formula
# Renames the class, records where it came from, makes it keg-only and adds
# the patch.  Exits 3 if an anchor is missing: Homebrew changed the
# formula's shape, and guessing would build something else.
#
# It also passes --disable-usbsid.  The bottle is built where libusb is not
# installed, so its configure leaves USBSID off (HAVE_USBSID no).  Here an
# unrelated libusb keg puts the header in reach, but Homebrew hides it from
# pkg-config because vice does not declare it, and configure stops.  The
# flag restores the bottle's choice; --check compares the two -features
# tables to catch any other difference of this kind.
generate_formula() {
    awk -v src="$1" -v psha="$2" -v purl="file://$(tap_patch)" '
        /^class Vice < Formula$/ && !cls {
            print "class ViceEth < Formula"
            print "  # Generated by c64-test-harness scripts/build-vice-eth.sh from"
            print "  # Homebrew\x27s vice formula plus vice/rawnet-bpf-permissions.patch. Do not edit."
            print "  # c64h-source-formula-sha256: " src
            print "  # c64h-patch-sha256: " psha
            print "  keg_only \"it is vice plus one patch, and would conflict with vice\""
            cls = 1
            next
        }
        /^    system "\.\/configure", / && !conf {
            sub(/system "\.\/configure", /, "system \"./configure\", \"--disable-usbsid\", ")
            conf = 1
        }
        /^  def install$/ && !inst {
            print "  patch do"
            print "    url \"" purl "\""
            print "    sha256 \"" psha "\""
            print "  end"
            print ""
            inst = 1
        }
        { print }
        END { if (!cls || !inst || !conf) exit 3 }'
}

# One field of `brew info --json=v2 vice` on stdin, or nothing.
api_field() { plutil -extract "formulae.0.$1" raw -o - - 2>/dev/null || true; }

# vice_source: Homebrew's current vice formula on stdout, byte for byte.
# Exits 2 (fail closed) when it cannot be read and verified.  A download that
# does not match the API's checksum is never replaced by `brew cat`: a
# mismatch is a reason to stop, not to look elsewhere.
vice_source() {
    local info path head want url tmp have why
    info="$(brew info --json=v2 vice 2>/dev/null)" || info=""
    path="$(printf '%s' "$info" | api_field ruby_source_path)"
    head="$(printf '%s' "$info" | api_field tap_git_head)"
    want="$(printf '%s' "$info" | api_field ruby_source_checksum.sha256)"
    if [ -n "$path" ] && [ -n "$head" ] && [ -n "$want" ]; then
        url="$CORE_RAW_URL/$head/$path"
        tmp="$(mktemp "${TMPDIR:-/tmp}/c64h-vice-formula.XXXXXX")"
        if curl -fsSL --connect-timeout 10 --max-time 60 -o "$tmp" "$url" 2>/dev/null; then
            have="$(sha256_of < "$tmp")"
            if [ "$have" != "$want" ]; then
                rm -f "$tmp"
                die "$url has sha256 $have, but brew info --json=v2 vice says $want; refusing it" 2
            fi
            cat "$tmp"
            rm -f "$tmp"
            return 0
        fi
        rm -f "$tmp"
        why="could not fetch $url"
    else
        why="brew info --json=v2 vice names no verifiable source (ruby_source_path, tap_git_head, ruby_source_checksum)"
    fi
    if [ -d "$(brew --repository homebrew/core)" ]; then
        say "$why; using brew cat vice from the local homebrew/core tap" >&2
        brew cat vice || die "brew cat vice failed too" 2
        return 0
    fi
    die "$why, and homebrew/core is not tapped, so brew cat vice cannot stand in" 2
}

# Drop the formula's bottle block (and the blank line after it).  A
# from-source build never reads it, a bottle rebuild rewrites only it, and
# left in it would point vice-eth at vice's bottles.
strip_bottle() {
    awk '/^  bottle do$/ && !done { skip = 1; next }
         skip { if ($0 == "  end") { skip = 0; done = 1; blank = 1 }; next }
         blank && $0 == "" { blank = 0; next }
         { blank = 0; print }'
}

current_formula() {
    local src src_sha patch_sha
    src="$(vice_source)" || exit $?
    src="$(printf '%s\n' "$src" | strip_bottle)"
    src_sha="$(printf '%s\n' "$src" | sha256_of)"
    patch_sha="$(sha256_of < "$PATCH")"
    printf '%s\n' "$src" | generate_formula "$src_sha" "$patch_sha" \
        || die "Homebrew's vice formula no longer has the shape this script edits (class line, def install or the configure call); update generate_formula" 3
}

# The recorded value of <key> in a generated formula on stdin.
recorded() { sed -n "s/^  # $1: //p" | head -1; }

installed_x64sc() { printf '%s/bin/x64sc\n' "$(brew --prefix "$NAME")"; }

# The -features table as "NAME value" lines, sorted, without the marker row.
feature_table() { "$1" -default -features 2>/dev/null | awk -v m="$MARKER" 'NF >= 2 && $1 != m && $2 ~ /^(yes|no)$/ { print $1, $2 }' | sort; }

# check: print why, return 0 current / 1 stale or diverged / 2 not built or not patched.
# 2 also covers a vice-eth that does not report the marker: the harness
# reads such a binary as stock and wants root for it, so it is no patched
# build as far as anyone running the harness is concerned.
check() {
    if ! brew list --versions "$TAP/$NAME" >/dev/null 2>&1; then
        say "not built: run scripts/build-vice-eth.sh"
        return 2
    fi
    if ! "$(installed_x64sc)" -default -features 2>/dev/null | grep -Eq "^[[:space:]]*$MARKER[[:space:]]+yes"; then
        say "not patched: $(installed_x64sc) does not report $MARKER yes, so the harness treats it as stock; rebuild"
        return 2
    fi
    local keg_formula want have key
    keg_formula="$(brew --prefix "$NAME")/.brew/$NAME.rb"
    [ -r "$keg_formula" ] || { say "stale: $keg_formula is missing; rebuild"; return 1; }
    if ! want="$(current_formula)"; then
        say "unknown: could not compare with Homebrew's vice formula (see above); the build is patched and runs as you"
        return 3
    fi
    for key in c64h-source-formula-sha256 c64h-patch-sha256; do
        have="$(recorded "$key" < "$keg_formula")"
        if [ "$have" != "$(printf '%s\n' "$want" | recorded "$key")" ]; then
            case "$key" in
                c64h-source-formula-sha256) say "stale: Homebrew's vice formula changed since this build (now $(brew list --versions vice 2>/dev/null || echo 'vice not installed')); rebuild" ;;
                *) say "stale: vice/rawnet-bpf-permissions.patch changed since this build; rebuild" ;;
            esac
            return 1
        fi
    done
    if [ ! -r "$(tap_patch)" ]; then
        say "stale: $(tap_patch) is missing, so a brew reinstall would fail; rebuild"
        return 1
    fi
    local stock diff note=""
    stock="$(brew --prefix vice)/bin/x64sc"
    if [ -x "$stock" ]; then
        diff="$(diff <(feature_table "$stock") <(feature_table "$(installed_x64sc)") | grep '^[<>]' || true)"
        if [ -n "$diff" ]; then
            say "diverged: -features differs from Homebrew's vice beyond $MARKER (< vice, > vice-eth):"
            printf '%s\n' "$diff" | sed 's/^/    /'
            return 1
        fi
    else
        note=" (not compared with Homebrew's vice: it is not installed)"
    fi
    say "current: $(brew list --versions "$TAP/$NAME") at $(installed_x64sc)$note"
    return 0
}

build() {
    local force="$1" tap_dir formula status=0
    if [ "$force" != "1" ]; then
        check || status=$?
        [ "$status" -eq 0 ] && return 0
    fi
    # Generated before anything is written, so a formula that cannot be
    # read or verified leaves the tap as it was.
    formula="$(current_formula)" || exit $?
    tap_dir="$(brew --repository "$TAP")"
    if [ ! -d "$tap_dir" ]; then
        say "creating local tap $TAP"
        brew tap-new --no-git "$TAP" >/dev/null
    fi
    mkdir -p "$tap_dir/Formula" "$tap_dir/patches"
    cp "$PATCH" "$(tap_patch)"
    printf '%s\n' "$formula" > "$tap_dir/Formula/$NAME.rb"
    say "building $TAP/$NAME from source (Homebrew's vice plus the patch)"
    # No auto-update: the formula was generated from what Homebrew's API
    # says now, and an update mid-run would make the record lie.
    if brew list --versions "$TAP/$NAME" >/dev/null 2>&1; then
        HOMEBREW_NO_AUTO_UPDATE=1 brew reinstall --build-from-source "$TAP/$NAME"
    else
        HOMEBREW_NO_AUTO_UPDATE=1 brew install --build-from-source "$TAP/$NAME"
    fi
    check || die "the build finished but --check does not pass (see above)"
}

main() {
    local mode="build" force=0
    while [ $# -gt 0 ]; do
        case "$1" in
            --check) mode="check" ;;
            --force) force=1 ;;
            --print-formula) mode="print" ;;
            -h|--help) sed -n '2,36p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
            *) die "unknown argument: $1" 2 ;;
        esac
        shift
    done
    [ "$(uname)" = "Darwin" ] || die "macOS only: on Linux VICE's tuntap driver needs no root" 2
    command -v brew >/dev/null 2>&1 || die "Homebrew (brew) not found on PATH" 2
    [ -r "$PATCH" ] || die "patch not found at $PATCH" 2
    case "$mode" in
        check) check ;;
        print) current_formula ;;
        build) build "$force" ;;
    esac
}

main "$@"
